"""Generate src/data/repos.ts from cached GitHub API dumps.

Inputs (fetched during the session, kept in ../_ref):
    gh-repos.json      /users/:owner/repos (per_page=100)
    lang-stats.json    /repos/:owner/:repo/languages for every repo
    readmes/*.md       READMEs for repos without a description

Usage: python _tools/gen_repos.py
"""

from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
REF = ROOT.parent / "_ref"
OUT = ROOT / "src" / "data" / "repos.ts"

SKIP = {"BaxterL"}  # profile-config repo
DB_LANGS = {"PLpgSQL", "SQL", "TSQL", "PLSQL", "MySQL", "SQLPL"}


def clean(text: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[`*_>#]", "", text)
    return " ".join(text.split())


def readme_summary(name: str) -> str:
    path = REF / "readmes" / f"{name}.md"
    if not path.exists():
        return ""
    picked: list[str] = []
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "![", "[![", "<", "|", "-", "```", "> ")):
            continue
        line = clean(line)
        if len(line) < 6:
            continue
        picked.append(line)
        if sum(len(p) for p in picked) > 70:
            break
    return " ".join(picked)[:120]


def main() -> None:
    repos = json.loads((REF / "gh-repos.json").read_text(encoding="utf-8"))
    stats: dict[str, dict[str, int]] = {}
    stats_path = REF / "lang-stats.json"
    if stats_path.exists():
        stats = json.loads(stats_path.read_text(encoding="utf-8"))

    rows = []
    totals: dict[str, int] = {}
    for r in repos:
        name = r["name"]
        if r.get("fork") or name in SKIP:
            continue
        breakdown = {
            lang: size
            for lang, size in (stats.get(name) or {}).items()
            if lang not in DB_LANGS
        }
        for lang, size in breakdown.items():
            totals[lang] = totals.get(lang, 0) + size
        repo_total = sum(breakdown.values()) or 1
        ranked = [
            (lang, round(size / repo_total * 100, 1))
            for lang, size in sorted(breakdown.items(), key=lambda kv: kv[1], reverse=True)
            if size / repo_total >= 0.05
        ][:3]
        dominant = ranked[0][0] if ranked else (r.get("language") or "")
        desc = (r.get("description") or "").strip() or readme_summary(name)
        rows.append(
            {
                "name": name,
                "desc": desc,
                "lang": dominant,
                "langs": ranked[:3],
                "created": (r.get("created_at") or "")[:7],
                "pushed": (r.get("pushed_at") or "")[:7],
                "url": r.get("html_url") or "",
                "home": r.get("homepage") or "",
                "archived": bool(r.get("archived")),
            }
        )

    rows.sort(key=lambda x: (x["pushed"], x["created"]), reverse=True)

    grand = sum(totals.values()) or 1
    mix = sorted(totals.items(), key=lambda kv: kv[1], reverse=True)[:6]
    mix_pct = [(lang, round(size / grand * 100, 1)) for lang, size in mix]

    lines = [
        "/** Generated by _tools/gen_repos.py from the GitHub API — do not hand-edit. */",
        "",
        "export interface RepoLang {",
        "  name: string",
        "  pct: number",
        "}",
        "",
        "export interface Repo {",
        "  name: string",
        "  desc: string",
        "  /** dominant code language, database dialects excluded */",
        "  lang: string",
        "  langs: RepoLang[]",
        "  created: string",
        "  pushed: string",
        "  url: string",
        "  home: string",
        "  archived: boolean",
        "}",
        "",
        f"/** {len(rows)} public repositories, newest push first. */",
        "export const REPOS: Repo[] = [",
    ]
    for row in rows:
        lines.append("  {")
        for key in ("name", "desc", "lang", "url", "home"):
            value = row[key].replace("\\", "\\\\").replace("'", "\\'")
            lines.append(f"    {key}: '{value}',")
        langs = ", ".join(f"{{ name: '{n}', pct: {p} }}" for n, p in row["langs"])
        lines.append(f"    langs: [{langs}],")
        lines.append(f"    created: '{row['created']}',")
        lines.append(f"    pushed: '{row['pushed']}',")
        lines.append(f"    archived: {'true' if row['archived'] else 'false'},")
        lines.append("  },")
    lines.append("]")
    lines.append("")
    lines.append("/** Share of code bytes across all public repos (database dialects excluded). */")
    lines.append("export const LANG_MIX: RepoLang[] = [")
    for lang, pct in mix_pct:
        lines.append(f"  {{ name: '{lang}', pct: {pct} }},")
    lines.append("]")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} repos, mix: {mix_pct})")


if __name__ == "__main__":
    main()
