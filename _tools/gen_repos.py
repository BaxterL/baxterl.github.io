"""Generate src/data/repos.ts from a cached GitHub /users/:owner/repos dump.

Usage:
    python _tools/gen_repos.py

Inputs (already fetched during the session):
    ../_ref/gh-repos.json      GitHub repos list (per_page=100)
    ../_ref/readmes/*.md       READMEs for repos without a description
"""

from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
REF = ROOT.parent / "_ref"
OUT = ROOT / "src" / "data" / "repos.ts"

SKIP = {"BaxterL"}  # profile-config repo


def clean(text: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[`*_>#]", "", text)
    return " ".join(text.split())


def readme_summary(name: str) -> str:
    path = REF / "readmes" / f"{name}.md"
    if not path.exists():
        return ""
    lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    picked: list[str] = []
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        if line.startswith(("#", "![", "[![", "<", "|", "-", "```", "> ")):
            continue
        line = clean(line)
        if len(line) < 6:
            continue
        picked.append(line)
        if sum(len(p) for p in picked) > 70:
            break
    return " ".join(picked)[:120]


def main() -> None:
    repos = json.loads((REF / "gh-repos.json").read_text(encoding="utf-8"))
    rows = []
    for r in repos:
        name = r["name"]
        if r.get("fork") or name in SKIP:
            continue
        desc = (r.get("description") or "").strip()
        if not desc:
            desc = readme_summary(name)
        rows.append(
            {
                "name": name,
                "desc": desc,
                "lang": r.get("language") or "",
                "stars": r.get("stargazers_count", 0),
                "created": (r.get("created_at") or "")[:7],
                "pushed": (r.get("pushed_at") or "")[:7],
                "url": r.get("html_url") or "",
                "home": r.get("homepage") or "",
                "archived": bool(r.get("archived")),
            }
        )

    rows.sort(key=lambda x: (x["pushed"], x["created"]), reverse=True)

    lines = [
        "/** Generated by _tools/gen_repos.py from the GitHub API — do not hand-edit. */",
        "",
        "export interface Repo {",
        "  name: string",
        "  desc: string",
        "  lang: string",
        "  stars: number",
        "  created: string",
        "  pushed: string",
        "  url: string",
        "  home: string",
        "  archived: boolean",
        "}",
        "",
        f"/** {len(rows)} public repositories, newest push first. */",
        "export const REPOS: Repo[] = [",
    ]
    for row in rows:
        lines.append("  {")
        for key in ("name", "desc", "lang", "url", "home"):
            value = row[key].replace("\\", "\\\\").replace("'", "\\'")
            lines.append(f"    {key}: '{value}',")
        lines.append(f"    stars: {row['stars']},")
        lines.append(f"    created: '{row['created']}',")
        lines.append(f"    pushed: '{row['pushed']}',")
        lines.append(f"    archived: {'true' if row['archived'] else 'false'},")
        lines.append("  },")
    lines.append("]")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} repos)")


if __name__ == "__main__":
    main()
